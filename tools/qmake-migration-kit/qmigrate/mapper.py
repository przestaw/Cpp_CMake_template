"""Generate a reviewable CMake draft and a mapping report from an exported qmake model.

The draft is a starting point, not a finished migration. Every construct the
mapper does not translate is listed in mapping-report.md/.json instead of being
dropped silently. Project-specific rules belong in an adapter JSON file
(see examples/demo/adapter.json), not in hand edits of the generated files.

Example:
    python3 map_to_cmake.py out/demo-release.json --output out/demo-draft \\
        --adapter examples/demo/adapter.json
    cmake -S out/demo-draft -B out/demo-draft-build
"""
