def cmake_quote(value: str) -> str:
    """Quote one CMake argument; keeps ${VAR} references that the mapper itself inserted."""
    return '"' + value.replace('\\', '/').replace('"', '\\"') + '"'


def cmake_quote_literal(value: str) -> str:
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$') + '"'


# Options whose argument is a separate word. CMake de-duplicates COMPILE_OPTIONS, so a
# repeated "-include" would be dropped and its file treated as an input: use SHELL:.
PAIRED_FLAGS = {'-include', '-imacros', '-isystem', '-iquote', '-idirafter', '-Xclang', '-mllvm',
                '-Xlinker', '-arch', '-target', '-x', '-Xcompiler', '-Xarch_x86_64', '-Xarch_arm64'}


def shell_unescape(value: str, windows: bool) -> str:
    """qmake writes DEFINES into the Makefile command line unchanged, so the shell (or the
    MSVC argument parser) removes one level of quoting. CMake escapes for us, so the
    value it needs is the one the compiler actually received."""
    if windows:
        out, i = [], 0
        while i < len(value):
            if value.startswith('\\"', i):
                out.append('"')
                i += 2
            elif value[i] == '"':
                i += 1
            else:
                out.append(value[i])
                i += 1
        return ''.join(out)
    try:
        parts = shlex.split(value, posix=True)
    except ValueError:
        return value
    return ' '.join(parts) if parts else ''


def sanitize(name: str) -> str:
    return re.sub(r'[^A-Za-z0-9_.+-]', '_', name) or 'target'


class Report:
    def __init__(self):
        self.items: list[dict] = []

    def add(self, project: str, severity: str, topic: str, detail: str):
        item = dict(project=project, severity=severity, topic=topic, detail=detail)
        if item not in self.items:
            self.items.append(item)

    def count(self, severity: str) -> int:
        return sum(1 for i in self.items if i['severity'] == severity)


class Mapper:
    def __init__(self, model: dict, records: dict[str, dict], adapter: dict, report: Report,
                 qt_mode: str = 'model', extra_components: dict | None = None):
        self.qt_mode = qt_mode
        self.extra_components = {k: set(v) for k, v in (extra_components or {}).items()}
        for key, value in adapter.get('qt6Components', {}).items():
            self.extra_components.setdefault(key, set()).update(value)
        self.components = {'common': set(), 'qt5': set(), 'qt6': set()}
        self.model = model
        self.records = records
        self.adapter = adapter
        self.report = report
        self.source_root = Path(model['sourceRoot'])
        self.run_dir = Path(model.get('runDir', '/nonexistent-run-dir'))
        self.qt_prefix = None
        self.need_pkgconfig = False
        self.need_threads = False
        self.targets: dict[str, str] = {}       # source -> cmake target
        self.lib_targets: dict[str, str] = {}   # qmake TARGET basename -> cmake target
        self.subdirs: dict[str, str] = {}       # source -> output subdir
        self._assign_names()

    # ---------- naming ----------
    def _assign_names(self):
        used = set()
        for source, record in sorted(self.records.items()):
            v = record['vars']
            template = (v.get('TEMPLATE') or ['app'])[0]
            rel_dir = PurePosixPath(source).parent.as_posix()
            self.subdirs[source] = '_root' if rel_dir == '.' else rel_dir
            if template in ('subdirs', 'aux'):
                continue
            name = sanitize((v.get('TARGET') or v.get('MIGRATION_TARGET_EFFECTIVE') or ['target'])[0])
            if name in used:
                unique = sanitize(f'{name}_{PurePosixPath(source).parent.name or "root"}')
                self.report.add(source, 'review', 'target name',
                                f'qmake TARGET {name!r} is not unique; CMake target renamed to '
                                f'{unique!r} (set OUTPUT_NAME if the file name must stay)')
                name = unique
            used.add(name)
            self.targets[source] = name
            if template in ('lib', 'vclib'):
                self.lib_targets[PurePosixPath((v.get('TARGET') or [name])[0]).name] = name

    # ---------- path mapping ----------
    def map_path(self, project: str, value: str, record: dict, kind: str = 'path',
                 relative_to_build: bool = False) -> str:
        """Map a qmake path. Relative paths resolve against the .pro directory, except
        custom-compiler outputs, which qmake resolves against OUT_PWD."""
        v = record['vars']
        pro_dir = Path(v['_PRO_FILE_PWD_'][0])
        out_pwd = Path(v.get('OUT_PWD', [str(self.run_dir)])[0])
        windows = self.is_windows(record)
        pure = PureWindowsPath(value) if windows else PurePosixPath(value)
        path = Path(value) if pure.is_absolute() else ((out_pwd if relative_to_build else pro_dir) / value)
        path = Path(os.path.normpath(str(path).replace('\\', '/')).replace('\\', '/'))
        for base, token in ((out_pwd, '${CMAKE_CURRENT_BINARY_DIR}'),
                            (self.source_root, '${MIGRATION_SOURCE_ROOT}')):
            try:
                rel = path.relative_to(base)
            except ValueError:
                continue
            return token if str(rel) == '.' else f'{token}/{rel.as_posix()}'
        if path.is_relative_to(self.run_dir):
            self.report.add(project, 'review', kind,
                            f'{value} points into another project\'s build tree; '
                            'replace with a target dependency')
            return path.as_posix()
        self.report.add(project, 'review', kind,
                        f'host-specific absolute path kept: {value} (map it in the adapter or a preset)')
        return path.as_posix()

    def effective_major(self, record: dict) -> str:
        if self.qt_mode in ('5', '6', 'dual'):
            return self.qt_mode
        return '6' if (record['vars'].get('QT_MAJOR_VERSION') or ['5'])[0] == '6' else '5'

    @staticmethod
    def is_windows(record: dict) -> bool:
        spec = record.get('meta', {}).get('xspec', '') or record.get('meta', {}).get('spec', '')
        return 'win32' in spec or 'msvc' in spec

    # ---------- per project ----------
    def project_cmake(self, source: str, record: dict) -> str:
        v = record['vars']
        template = (v.get('TEMPLATE') or ['app'])[0]
        config = v.get('CONFIG', [])
        lines = [GENERATED_BANNER, f'# qmake project: {source}\n']
        if template == 'subdirs':
            lines.append('# SUBDIRS project: children are added by the top-level CMakeLists.txt.\n')
            return ''.join(lines)
        for var in sorted(v):
            if var not in HANDLED_VARS and var not in self.adapter.get('ignoreVars', []) and v[var]:
                severity = 'unsupported' if var in (
                    'QMAKE_PRE_LINK', 'QMAKE_POST_LINK', 'LEXSOURCES', 'YACCSOURCES',
                    'QMAKE_EXTRA_TARGETS', 'QMAKE_SUBSTITUTES', 'TRANSLATIONS') else 'review'
                self.report.add(source, severity, 'variable', f'{var} = {" ".join(v[var])}')
        for word, meaning in REPORTED_CONFIG.items():
            if word in config:
                self.report.add(source, 'review', 'CONFIG', f'{word}: {meaning} is not mapped')

        outputs = {o for c in record.get('compilers', {}).values() for o in c.get('output', [])}
        build_dirs = [Path(r['vars'].get('OUT_PWD', ['/nonexistent'])[0]) for r in self.records.values()]
        for dep in v.get('PRE_TARGETDEPS', []) + v.get('POST_TARGETDEPS', []):
            dep_path = Path(os.path.normpath(dep))
            if dep in outputs:
                continue
            if dep_path.is_absolute() and (dep_path.is_relative_to(self.run_dir) or
                                           any(dep_path.is_relative_to(b) for b in build_dirs)):
                self.report.add(source, 'info', 'PRE_TARGETDEPS',
                                f'{dep}: build-tree relink trigger; covered by target_link_libraries')
            else:
                self.report.add(source, 'review', 'PRE_TARGETDEPS', f'{dep}: map to a DEPENDS or a target')

        if template == 'aux':
            target = None
        else:
            target = self.targets[source]
            lines += self.target_definition(source, record, template, config, target)
        lines += self.extra_compilers(source, record, target)
        lines += self.installs(source, record, target, template)
        return ''.join(lines)

    def target_definition(self, source, record, template, config, target) -> list[str]:
        v = record['vars']
        out = []
        files = []
        for var in ('SOURCES', 'HEADERS', 'FORMS', 'RESOURCES', 'OBJECTIVE_SOURCES'):
            files += [self.map_path(source, f, record, var) for f in v.get(var, [])]
        if v.get('OBJECTIVE_SOURCES'):
            self.report.add(source, 'review', 'OBJECTIVE_SOURCES', 'enable OBJCXX and check flags')
        windows = self.is_windows(record)
        for var in ('RC_FILE', 'DEF_FILE'):
            for f in v.get(var, []):
                files.append(self.map_path(source, f, record, var))
                self.report.add(source, 'review', var, f'{f} added as a source; verify on MSVC')
        qt_major = (v.get('QT_MAJOR_VERSION') or ['5'])[0]
        if template in ('lib', 'vclib'):
            if 'staticlib' in config or 'static' in config and 'shared' not in config:
                kind = 'STATIC'
            elif 'plugin' in config:
                kind = 'MODULE'
            else:
                kind = 'SHARED'
            out.append(f'add_library({target} {kind})\n')
        else:
            exe_props = []
            if windows and 'console' not in config:
                exe_props.append('WIN32')
            if 'app_bundle' in config and 'macx' in record.get('meta', {}).get('xspec', ''):
                exe_props.append('MACOSX_BUNDLE')
            out.append(f'add_executable({target}{"".join(" " + p for p in exe_props)})\n')
        if files:
            out.append(f'target_sources({target} PRIVATE\n' +
                       ''.join(f'    {cmake_quote(f)}\n' for f in files) + ')\n')

        props = {}
        standards = [CXX_STANDARDS[c] for c in config if c in CXX_STANDARDS]
        qt_major_effective = self.effective_major(record)
        if v.get('QT') and max(standards, default=0) < 17:
            if qt_major_effective == '6':
                self.report.add(source, 'info', 'C++ standard',
                                f'raised to C++17 for Qt 6 (was {max(standards) if standards else "unset"})')
                standards.append(17)
            elif qt_major_effective == 'dual':
                self.report.add(source, 'info', 'C++ standard',
                                'kept for Qt 5; with Qt 6 the cxx_std_17 compile feature of Qt6::Platform raises it to C++17')
        if standards:
            props['CXX_STANDARD'] = str(max(standards))
            props['CXX_STANDARD_REQUIRED'] = 'ON'
            # qmake selects -std=gnu++NN on GCC/Clang unless strict_c++ is set.
            props['CXX_EXTENSIONS'] = 'OFF' if 'strict_c++' in config else 'ON'
            if 'strict_c++' not in config and not windows:
                self.report.add(source, 'info', 'C++ standard',
                                'CXX_EXTENSIONS ON mirrors qmake gnu++NN; add CONFIG+=strict_c++ '
                                'in qmake or switch it OFF deliberately')
        qt_modules = v.get('QT', []) + v.get('QT_PRIVATE', [])
        if qt_modules:
            props['AUTOMOC'] = 'ON'
        if v.get('FORMS'):
            props['AUTOUIC'] = 'ON'
            ui_dirs = sorted({str(PurePosixPath(self.map_path(source, f, record, 'FORMS')).parent)
                              for f in v['FORMS']})
            props['AUTOUIC_SEARCH_PATHS'] = ';'.join(ui_dirs)
        if v.get('RESOURCES'):
            props['AUTORCC'] = 'ON'
        if 'ltcg' in config:
            props['INTERPROCEDURAL_OPTIMIZATION'] = 'ON'
        if v.get('VERSION') and template in ('lib', 'vclib') and 'plugin' not in config:
            version = v['VERSION'][0]
            props['VERSION'] = version
            props['SOVERSION'] = version.split('.')[0]
        if props:
            out.append(f'set_target_properties({target} PROPERTIES\n' +
                       ''.join(f'    {k} {cmake_quote(val)}\n' for k, val in props.items()) + ')\n')

        # qmake adds the project directory and the build directory to the include path.
        includes = [] if 'no_include_pwd' in config else ['${MIGRATION_SOURCE_ROOT}/' +
                                                          PurePosixPath(source).parent.as_posix(),
                                                          '${CMAKE_CURRENT_BINARY_DIR}']
        includes = [i.replace('/.', '') if i.endswith('/.') else i for i in includes]
        for inc in v.get('INCLUDEPATH', []):
            mapped = self.map_path(source, inc, record, 'INCLUDEPATH')
            if mapped not in includes:
                includes.append(mapped)
        if includes:
            out.append(f'target_include_directories({target} PRIVATE\n' +
                       ''.join(f'    {cmake_quote(i)}\n' for i in includes) + ')\n')

        defines = []
        drop = set(self.adapter.get('dropDefines', []))
        for d in v.get('DEFINES', []):
            if QT_MANAGED_DEFINE.match(d) or d in drop:
                continue
            if any(ch in d for ch in '"\\\''):
                value = shell_unescape(d, windows)
                self.report.add(source, 'info', 'DEFINES',
                                f'{d}: one level of shell quoting removed -> {value} (what the compiler received '
                                'from qmake); confirm with `qmig compare`')
                d = value
            if ';' in d:
                self.report.add(source, 'unsupported', 'DEFINES', f'{d}: ";" splits a CMake list')
                continue
            defines.append(d)
        if 'no_keywords' in config and 'QT_NO_KEYWORDS' not in defines:
            defines.append('QT_NO_KEYWORDS')
        if 'plugin' in config and 'designer' in config:
            # Mirrors designer_defines.prf: only this plugin target exports widgets.
            defines.append('QDESIGNER_EXPORT_WIDGETS')
        if defines:
            out.append(f'target_compile_definitions({target} PRIVATE\n' +
                       ''.join(f'    {cmake_quote_literal(d)}\n' for d in defines) + ')\n')

        options = []
        drop_flags = set(self.adapter.get('dropFlags', []))
        for var, lang in (('QMAKE_CXXFLAGS', 'CXX'), ('QMAKE_CFLAGS', 'C')):
            flags = v.get(var, [])
            index = 0
            while index < len(flags):
                flag = flags[index]
                index += 1
                if TOOLCHAIN_FLAG.match(flag) or flag in drop_flags:
                    continue
                if flag in PAIRED_FLAGS and index < len(flags):
                    arg = flags[index]
                    index += 1
                    if arg.startswith('/') or Path(arg).is_absolute():
                        arg = self.map_path(source, arg, record, var)
                    quoted = f'"{arg}"' if ' ' in arg else arg
                    options.append(f'$<$<COMPILE_LANGUAGE:{lang}>:SHELL:{flag} {quoted}>')
                    self.report.add(source, 'info', var, f'{flag} {arg}: kept as SHELL: option '
                                                         '(CMake would otherwise de-duplicate the option word)')
                    continue
                if ' ' in flag:
                    self.report.add(source, 'review', var, f'{flag!r}: one qmake item with spaces; the compiler '
                                                           'received separate words, CMake passes one argument')
                options.append(f'$<$<COMPILE_LANGUAGE:{lang}>:{flag}>')
                self.report.add(source, 'review', var, f'{flag} kept as a target option')
        if self.adapter.get('matchQmakeDefaults') and 'warn_on' in config:
            options[:0] = ['$<$<CXX_COMPILER_ID:MSVC>:/W3>', '$<$<NOT:$<CXX_COMPILER_ID:MSVC>>:-Wall;-Wextra>']
            windows = False  # these options are already compiler-guarded
        if options:
            options = list(dict.fromkeys(options))
            guard = 'if(MSVC)\n' if windows else ''
            out.append(f'{guard}target_compile_options({target} PRIVATE\n' +
                       ''.join(f'    {cmake_quote(o)}\n' for o in options) + ')\n' +
                       ('endif()\n' if guard else ''))
        link_opts = [f for f in v.get('QMAKE_LFLAGS', [])
                     if not TOOLCHAIN_FLAG.match(f) and f not in drop_flags]
        for flag in link_opts:
            self.report.add(source, 'review', 'QMAKE_LFLAGS', f'{flag} kept as a link option')
        if link_opts:
            out.append(f'target_link_options({target} PRIVATE\n' +
                       ''.join(f'    {cmake_quote(f)}\n' for f in link_opts) + ')\n')

        if 'precompile_header' in config and v.get('PRECOMPILED_HEADER'):
            pch = self.map_path(source, v['PRECOMPILED_HEADER'][0], record, 'PRECOMPILED_HEADER')
            out.append(f'target_precompile_headers({target} PRIVATE {cmake_quote(pch)})\n')

        links = self.link_items(source, record, template, qt_major)
        for scope in ('PUBLIC', 'PRIVATE'):
            if links[scope]:
                out.append(f'target_link_libraries({target} {scope}\n' +
                           ''.join(f'    {l}\n' for l in dict.fromkeys(links[scope])) + ')\n')
        for condition, key in (('QT_VERSION_MAJOR GREATER_EQUAL 6', 'only6'), ('QT_VERSION_MAJOR EQUAL 5', 'only5')):
            if links[key]:
                scope = 'PUBLIC' if template in ('lib', 'vclib') else 'PRIVATE'
                out.append(f'if({condition})\n    target_link_libraries({target} {scope}\n' +
                           ''.join(f'        {l}\n' for l in dict.fromkeys(links[key])) + '    )\nendif()\n')
        if links['dirs']:
            out.append(f'target_link_directories({target} PRIVATE\n' +
                       ''.join(f'    {cmake_quote(d)}\n' for d in links['dirs']) + ')\n')
        return out

    def link_items(self, source, record, template, qt_major) -> dict:
        v = record['vars']
        links = {'PUBLIC': [], 'PRIVATE': [], 'dirs': [], 'only6': [], 'only5': []}
        is_lib = template in ('lib', 'vclib')
        mode = self.effective_major(record)
        prefix = {'5': 'Qt5', '6': 'Qt6', 'dual': 'Qt'}[mode]
        if mode == 'dual':
            self.report.add(source, 'info', 'QT', 'versionless Qt:: targets need Qt 5.15 or Qt 6')
        for var, scope in (('QT', 'PUBLIC' if is_lib else 'PRIVATE'), ('QT_PRIVATE', 'PRIVATE')):
            for module in v.get(var, []):
                if module.endswith('-private'):
                    self.report.add(source, 'unsupported', 'QT',
                                    f'{module}: private Qt headers need <Module>_PRIVATE_INCLUDE_DIRS (Qt 5) '
                                    'or Qt6::<Module>Private (Qt 6)')
                    continue
                name5 = QT_MODULES.get(module)
                name6 = QT6_MODULES.get(module, (None,))[0]
                if mode == '5':
                    names = [(name5, 'PUBLIC_OR_PRIVATE', '5')]
                elif mode == '6':
                    names = [(name6, 'PUBLIC_OR_PRIVATE', '6')]
                elif name5 and name5 == name6:
                    names = [(name5, 'PUBLIC_OR_PRIVATE', 'common')]
                else:
                    names = [(name5, 'only5', '5'), (name6, 'only6', '6')]
                for name, bucket, major in names:
                    if not name:
                        self.report.add(source, 'unsupported', 'QT', f'Qt module {module!r} has no Qt {major} '
                                                                      'equivalent (see qmig qt6)')
                        continue
                    self.components[{'5': 'qt5', '6': 'qt6', 'common': 'common'}[major]].add(name)
                    links[scope if bucket == 'PUBLIC_OR_PRIVATE' else bucket].append(f'{prefix}::{name}')
        extra = sorted(self.extra_components.get(source, ()))
        for name in extra:
            if mode == '5':
                self.report.add(source, 'review', 'QT', f'{name} requested for Qt 6 but the draft targets Qt 5')
                continue
            if mode == 'dual' and name in QT6_ONLY_COMPONENTS:
                self.components['qt6'].add(name)
                links['only6'].append(f'Qt::{name}')
            else:
                self.components['qt6' if mode == '6' else 'common'].add(name)
                links['PRIVATE'].append(f'{prefix}::{name}')
            self.report.add(source, 'info', 'QT', f'{name} added for Qt 6 (source scan / adapter)')
        self.qt_prefix = self.qt_prefix or prefix
        if is_lib and v.get('QT'):
            self.report.add(source, 'info', 'QT', 'library links Qt PUBLIC (headers usually expose Qt '
                                                  'types); narrow to PRIVATE where they do not')
        if v.get('PKGCONFIG'):
            self.need_pkgconfig = True
            for pkg in v['PKGCONFIG']:
                links['PRIVATE'].append(f'PkgConfig::{sanitize(pkg).upper()}')
        lib_map = self.adapter.get('libs', {})
        build_tree = [Path(r['vars'].get('OUT_PWD', ['/nonexistent'])[0]) for r in self.records.values()]
        tokens = v.get('LIBS', []) + v.get('LIBS_PRIVATE', [])
        index = 0
        while index < len(tokens):
            token = tokens[index]
            index += 1
            if token in lib_map:
                links['PRIVATE'].append(lib_map[token])
            elif token == '-framework' and index < len(tokens):
                links['PRIVATE'].append(cmake_quote(f'-framework {tokens[index]}'))
                self.report.add(source, 'review', 'LIBS', f'-framework {tokens[index]}')
                index += 1
            elif token.startswith('-L'):
                path = Path(token[2:])
                if any(path == b or path.is_relative_to(b) or b.is_relative_to(path) for b in build_tree) \
                        or path.is_relative_to(self.run_dir):
                    self.report.add(source, 'info', 'LIBS', f'{token}: build-tree link directory dropped')
                else:
                    links['dirs'].append(self.map_path(source, token[2:], record, 'LIBS'))
            elif token in ('-lpthread', '-pthread'):
                self.need_threads = True
                links['PRIVATE'].append('Threads::Threads')
            elif token.startswith('-l'):
                name = token[2:]
                if name in self.lib_targets:
                    links['PRIVATE'].append(self.lib_targets[name])
                else:
                    links['PRIVATE'].append(name)
                    self.report.add(source, 'review', 'LIBS',
                                    f'{token}: plain library name; map to an imported target in the adapter')
            elif token.startswith('-') or token.startswith('/'):
                if re.search(r'\.(so[.\d]*|a|lib|dylib)$', token):
                    links['PRIVATE'].append(cmake_quote(self.map_path(source, token, record, 'LIBS')))
                else:
                    links['PRIVATE'].append(cmake_quote(token))
                    self.report.add(source, 'review', 'LIBS', f'{token}: linker option passed through')
            else:
                links['PRIVATE'].append(cmake_quote(self.map_path(source, token, record, 'LIBS')))
                self.report.add(source, 'review', 'LIBS', f'{token}: library file path')
        return links

    # ---------- custom compilers ----------
    def extra_compilers(self, source, record, target) -> list[str]:
        out = []
        tools = self.adapter.get('tools', {})
        windows = self.is_windows(record)
        for name, data in record.get('compilers', {}).items():
            where = f'QMAKE_EXTRA_COMPILERS {name}'
            cfg = data.get('CONFIG', [])
            problems = []
            if data.get('output_function'):
                problems.append('output_function')
            if data.get('depend_command'):
                self.report.add(source, 'review', where, 'depend_command has no direct equivalent; '
                                                         'use DEPFILE or explicit DEPENDS')
            if len(data.get('output', [])) != 1:
                problems.append('output must be a single pattern')
            command_text = ' '.join(data.get('commands', []))
            if not command_text:
                problems.append('no commands')
            if '\n' in command_text or '$$' in command_text:
                problems.append('multi-line or unexpanded command')
            if problems:
                self.report.add(source, 'unsupported', where, '; '.join(problems))
                out.append(f'# UNSUPPORTED {where}: {"; ".join(problems)}\n')
                continue
            try:
                argv = shlex.split(command_text, posix=not windows)
            except ValueError as error:
                self.report.add(source, 'unsupported', where, f'cannot tokenize command: {error}')
                continue
            inputs = [(var, item) for var, items in data.get('inputs', {}).items() for item in items]
            if not inputs:
                self.report.add(source, 'info', where, 'no input files in this configuration')
                continue
            combine = 'combine' in cfg
            groups = [inputs] if combine else [[i] for i in inputs]
            produced = []
            for group in groups:
                in_paths = [self.map_path(source, item, record, where) for _, item in group]
                first = group[0][1]
                base = PurePosixPath(first.replace('\\', '/'))
                subst = {
                    'QMAKE_FILE_IN': in_paths, 'QMAKE_FILE_NAME': in_paths,
                    'QMAKE_FILE_BASE': [base.stem], 'QMAKE_FILE_IN_BASE': [base.stem],
                    'QMAKE_FILE_EXT': [base.suffix], 'QMAKE_FILE_IN_EXT': [base.suffix],
                    'QMAKE_FILE_PATH': [str(PurePosixPath(in_paths[0]).parent)],
                    'QMAKE_FILE_IN_PATH': [str(PurePosixPath(in_paths[0]).parent)],
                }
                output = data['output'][0]
                for key in ('QMAKE_FILE_BASE', 'QMAKE_FILE_IN_BASE', 'QMAKE_FILE_EXT', 'QMAKE_FILE_IN_EXT'):
                    output = output.replace('${' + key + '}', subst[key][0])
                if PLACEHOLDER.search(output):
                    self.report.add(source, 'unsupported', where, f'output placeholder in {output}')
                    break
                out_path = self.map_path(source, output, record, where, relative_to_build=True)
                subst['QMAKE_FILE_OUT'] = [out_path]
                out_p = PurePosixPath(out_path)
                subst['QMAKE_FILE_OUT_BASE'] = [out_p.stem]
                subst['QMAKE_FILE_OUT_PATH'] = [str(out_p.parent)]
                args, failed = [], False
                deps = list(in_paths) + [self.map_path(source, d, record, where)
                                         for d in data.get('depends', [])]
                for token in argv:
                    if token in SHELL_SYNTAX:
                        self.report.add(source, 'review', where,
                                        f'shell syntax {token!r}; VERBATIM commands are not run through a shell '
                                        'on every generator')
                    if token in tools:
                        args.append(tools[token])
                        continue
                    if token in subst:
                        args += subst[token]
                        continue
                    whole = re.fullmatch(r'\$\{(QMAKE_[A-Z_]+)\}', token)
                    if whole and whole.group(1) in subst:
                        args += subst[whole.group(1)]
                        continue
                    for key, values in subst.items():
                        token = token.replace('${' + key + '}', ' '.join(values))
                    if PLACEHOLDER.search(token):
                        self.report.add(source, 'unsupported', where, f'placeholder in {token}')
                        failed = True
                        break
                    if (PureWindowsPath(token) if windows else PurePosixPath(token)).is_absolute():
                        mapped = self.map_path(source, token, record, where)
                        args.append(mapped)
                        if mapped.startswith('${MIGRATION_SOURCE_ROOT}') and mapped not in deps:
                            deps.append(mapped)
                            self.report.add(source, 'info', where,
                                            f'{token} is used by the command; added to DEPENDS '
                                            '(qmake did not track it)')
                    else:
                        if token == argv[0] and token not in tools:
                            self.report.add(source, 'review', where,
                                            f'tool {token!r} taken from PATH; map it in adapter "tools"')
                        args.append(token)
                if failed:
                    break
                out.append(f'add_custom_command(\n    OUTPUT {cmake_quote(out_path)}\n'
                           f'    COMMAND {" ".join(cmake_quote(a) for a in args)}\n'
                           f'    DEPENDS {" ".join(cmake_quote(d) for d in dict.fromkeys(deps))}\n'
                           f'    COMMENT "{name}: {PurePosixPath(out_path).name}"\n    VERBATIM)\n')
                produced.append(out_path)
            if not produced:
                continue
            var_out = (data.get('variable_out') or ['SOURCES'])[0]
            if target is None:
                out.append(f'add_custom_target({sanitize(source)}_{name} ALL DEPENDS\n' +
                           ''.join(f'    {cmake_quote(p)}\n' for p in produced) + ')\n')
                continue
            out.append(f'target_sources({target} PRIVATE\n' +
                       ''.join(f'    {cmake_quote(p)}\n' for p in produced) + ')\n')
            compiled = var_out in ('SOURCES', 'GENERATED_SOURCES') and 'no_link' not in cfg
            if not compiled:
                compile_like = [p for p in produced if re.search(r'\.(c|cc|cpp|cxx)$', p)]
                if compile_like:
                    out.append('set_source_files_properties(\n' +
                               ''.join(f'    {cmake_quote(p)}\n' for p in compile_like) +
                               '    PROPERTIES HEADER_FILE_ONLY ON)\n')
            if var_out not in ('SOURCES', 'GENERATED_SOURCES', 'HEADERS', 'GENERATED_FILES'):
                self.report.add(source, 'review', where, f'variable_out {var_out} is not mapped')
        return out

    # ---------- installs ----------
    def install_destination(self, source, path: str) -> str:
        for old, new in self.adapter.get('installPaths', {}).items():
            if path == old or path.startswith(old.rstrip('/') + '/'):
                path = new + path[len(old):]
                break
        if re.match(r'^[A-Za-z]:[/\\]', path):
            self.report.add(source, 'review', 'INSTALLS', f'drive letter dropped from {path}')
            path = path[2:]
        if path.startswith(('/', '\\')):
            self.report.add(source, 'info', 'INSTALLS',
                            'absolute qmake install paths are mapped below CMAKE_INSTALL_PREFIX '
                            '(same layout as qmake INSTALL_ROOT)')
        if '$' in path:
            self.report.add(source, 'review', 'INSTALLS', f'unexpanded variable in path {path}')
        return path.strip('/\\') or '.'

    def installs(self, source, record, target, template) -> list[str]:
        out = []
        pro_dir = Path(record['vars']['_PRO_FILE_PWD_'][0])
        for name, data in record.get('installs', {}).items():
            where = f'INSTALLS {name}'
            if data.get('extra') or data.get('commands'):
                self.report.add(source, 'unsupported', where, 'extra/commands need install(CODE) or install(SCRIPT)')
            if not data.get('path'):
                self.report.add(source, 'review', where, 'no path')
                continue
            dest = cmake_quote(self.install_destination(source, data['path'][0]))
            component = f'COMPONENT {sanitize(name)}'
            cfg = data.get('CONFIG', [])
            optional = ' OPTIONAL' if 'no_check_exist' in cfg else ''
            if name == 'target' and not data.get('files'):
                if target is None:
                    continue
                out.append(f'install(TARGETS {target}\n    RUNTIME DESTINATION {dest} {component}\n'
                           f'    LIBRARY DESTINATION {dest} {component}\n'
                           f'    ARCHIVE DESTINATION {dest} {component})\n')
                continue
            files, dirs = [], []
            for item in data.get('files', []):
                mapped = self.map_path(source, item, record, where)
                if any(ch in item for ch in '*?['):
                    var = f'_mig_{sanitize(name)}_{len(files)}'
                    out.append(f'file(GLOB {var} {cmake_quote(mapped)})\n')
                    files.append('${' + var + '}')
                    self.report.add(source, 'review', where, f'glob {item} evaluated at configure time')
                    continue
                abs_path = Path(item) if Path(item).is_absolute() else pro_dir / item
                if abs_path.is_dir():
                    dirs.append(mapped)
                else:
                    if not abs_path.exists() and 'no_check_exist' not in cfg \
                            and not mapped.startswith('${CMAKE_CURRENT_BINARY_DIR}'):
                        self.report.add(source, 'review', where, f'{item} does not exist at export time')
                    files.append(mapped)
            verb = 'PROGRAMS' if 'executable' in cfg else 'FILES'
            if files:
                out.append(f'install({verb}\n' + ''.join(f'    {cmake_quote(f)}\n' for f in files) +
                           f'    DESTINATION {dest} {component}{optional})\n')
            for d in dirs:
                out.append(f'install(DIRECTORY {cmake_quote(d)} DESTINATION {dest} {component}{optional})\n')
        return out

    # ---------- subdirs ----------
    def subdir_dependencies(self) -> list[str]:
        out = []
        for source, record in sorted(self.records.items()):
            if (record['vars'].get('TEMPLATE') or [''])[0] != 'subdirs':
                continue
            pro_dir = PurePosixPath(source).parent

            def resolve(item: str):
                data = record.get('subdirs', {}).get(item, {})
                rel = (data.get('file') or data.get('subdir') or [item])[0]
                candidate = PurePosixPath(rel) if PurePosixPath(rel).is_absolute() else pro_dir / rel
                text = candidate.as_posix()
                if text.startswith(str(self.source_root)):
                    text = PurePosixPath(text).relative_to(PurePosixPath(str(self.source_root))).as_posix()
                options = [text] if text.endswith('.pro') else [f'{text}/{PurePosixPath(text).name}.pro']
                for opt in options:
                    opt = PurePosixPath(opt).as_posix().removeprefix('./')
                    if opt in self.targets:
                        return self.targets[opt]
                return None

            for item in record['vars'].get('SUBDIRS', []):
                deps = record.get('subdirs', {}).get(item, {}).get('depends', [])
                if not deps:
                    continue
                me = resolve(item)
                for dep in deps:
                    other = resolve(dep)
                    if me and other:
                        out.append(f'add_dependencies({me} {other})\n')
                    else:
                        self.report.add(source, 'review', 'SUBDIRS',
                                        f'{item}.depends = {dep} could not be resolved to targets '
                                        '(export with --recursive)')
        return out


def write_report(path_md: Path, path_json: Path, report: Report, model: dict, records: dict):
    path_json.write_text(json.dumps(dict(profile=model.get('profile'), sourceRoot=model['sourceRoot'],
                                         projects=sorted(records), items=report.items),
                                    indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
    lines = [f'# Mapping report: {model.get("profile")}\n\n',
             f'Projects: {len(records)}. unsupported: {report.count("unsupported")}, '
             f'review: {report.count("review")}, info: {report.count("info")}.\n\n',
             'A draft with open `unsupported` items is not a finished migration.\n']
    for severity in ('unsupported', 'review', 'info'):
        items = [i for i in report.items if i['severity'] == severity]
        if not items:
            continue
        lines.append(f'\n## {severity} ({len(items)})\n\n| Project | Topic | Detail |\n| --- | --- | --- |\n')
        for i in items:
            detail = i['detail'].replace('|', '\\|')
            lines.append(f'| `{i["project"]}` | {i["topic"]} | {detail} |\n')
    path_md.write_text(''.join(lines), encoding='utf-8')


def generate(model: dict, records: dict, output: Path, *, adapter: dict, qt_mode: str = 'model',
             extra_components: dict | None = None, project_name: str = 'MigratedProject') -> Report:
    if output.exists():
        raise ValueError(f'{output} exists; an existing draft is never overwritten')
    report = Report()
    mapper = Mapper(model, records, adapter, report, qt_mode, extra_components)
    files = {}
    for source, record in sorted(records.items()):
        files[mapper.subdirs[source]] = mapper.project_cmake(source, record)
    deps = mapper.subdir_dependencies()
    comps = mapper.components
    top = [GENERATED_BANNER, 'cmake_minimum_required(VERSION 3.21)\n',
           f'project({sanitize(project_name)} LANGUAGES C CXX)\n',
           f'set(MIGRATION_SOURCE_ROOT {cmake_quote(model["sourceRoot"])} CACHE PATH '
           '"qmake source tree the draft refers to")\n']
    if mapper.qt_prefix == 'Qt':
        top.append('set(QMIG_QT_MAJOR "" CACHE STRING "Qt major for this dual draft: 5, 6, or empty = Qt6 if found")\n'
                   'if(QMIG_QT_MAJOR)\n    find_package(QT NAMES Qt${QMIG_QT_MAJOR} REQUIRED COMPONENTS Core)\n'
                   'else()\n    find_package(QT NAMES Qt6 Qt5 REQUIRED COMPONENTS Core)\nendif()\n'
                   'message(STATUS "Qt major selected for the draft: ${QT_VERSION_MAJOR}")\n')
        if comps['common']:
            top.append(f'find_package(Qt${{QT_VERSION_MAJOR}} REQUIRED COMPONENTS {" ".join(sorted(comps["common"]))})\n')
        if comps['qt6']:
            top.append(f'if(QT_VERSION_MAJOR GREATER_EQUAL 6)\n    find_package(Qt6 REQUIRED COMPONENTS '
                       f'{" ".join(sorted(comps["qt6"]))})\nendif()\n')
        if comps['qt5']:
            top.append(f'if(QT_VERSION_MAJOR EQUAL 5)\n    find_package(Qt5 REQUIRED COMPONENTS '
                       f'{" ".join(sorted(comps["qt5"]))})\nendif()\n')
    elif mapper.qt_prefix:
        names = sorted(comps['common'] | comps['qt5'] | comps['qt6'])
        if names:
            top.append(f'find_package({mapper.qt_prefix} REQUIRED COMPONENTS {" ".join(names)})\n')
    if adapter.get('matchQmakeDefaults'):
        top.append('# Adapter matchQmakeDefaults: qmake release semantics (no NDEBUG, mkspec optimisation level).\n'
                   'if(CMAKE_CXX_COMPILER_ID MATCHES "GNU|Clang" AND NOT MSVC)\n'
                   '    set(CMAKE_C_FLAGS_RELEASE "-O2")\n    set(CMAKE_CXX_FLAGS_RELEASE "-O2")\n'
                   '    if(NOT APPLE)\n'
                   '        foreach(_kind EXE SHARED MODULE)\n'
                   '            set(CMAKE_${_kind}_LINKER_FLAGS_RELEASE "-Wl,-O1")\n'
                   '        endforeach()\n    endif()\n'
                   'elseif(MSVC)\n    set(CMAKE_C_FLAGS_RELEASE "/O2")\n    set(CMAKE_CXX_FLAGS_RELEASE "/O2")\nendif()\n')
        report.add('(top level)', 'info', 'build type',
                   'Release flags follow qmake (assert() stays active: no NDEBUG); remove the adapter key to use CMake defaults')
    else:
        report.add('(top level)', 'info', 'build type',
                   'CMake Release adds NDEBUG (assert() compiled out) and -O3 on GCC; qmake release does neither. '
                   'Decide deliberately or set adapter "matchQmakeDefaults": true')
    if mapper.need_threads:
        top.append('find_package(Threads REQUIRED)\n')
    if mapper.need_pkgconfig:
        top.append('find_package(PkgConfig REQUIRED)\n')
        pkgs = sorted({p for r in records.values() for p in r['vars'].get('PKGCONFIG', [])})
        for pkg in pkgs:
            top.append(f'pkg_check_modules({sanitize(pkg).upper()} REQUIRED IMPORTED_TARGET GLOBAL {pkg})\n')
    for package in adapter.get('findPackages', []):
        top.append(f'find_package({package})\n')
    for subdir in sorted(files):
        top.append(f'add_subdirectory({cmake_quote(subdir)})\n')
    top += deps

    output.mkdir(parents=True)
    (output / 'CMakeLists.txt').write_text(''.join(top), encoding='utf-8')
    for subdir, text in files.items():
        directory = output / subdir
        directory.mkdir(parents=True, exist_ok=True)
        (directory / 'CMakeLists.txt').write_text(text, encoding='utf-8')
    write_report(output / 'mapping-report.md', output / 'mapping-report.json', report, model, records)
    return report


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('model', type=Path)
    parser.add_argument('--output', type=Path, required=True, help='New directory for the draft')
    parser.add_argument('--adapter', type=Path, help='Project-specific mapping rules (JSON)')
    parser.add_argument('--variant', choices=['debug', 'release'], help='Select debug_and_release records')
    parser.add_argument('--qt', choices=['model', '5', '6', 'dual'], default='model',
                        help='Qt major for the draft; dual = versionless Qt:: targets for Qt 5.15 and Qt 6')
    parser.add_argument('--qt6-report', type=Path, help='qmig qt6 JSON report: adds required components')
    parser.add_argument('--project-name', default='MigratedProject')
    parser.add_argument('--allow-incomplete', action='store_true')
    parser.add_argument('--strict', action='store_true', help='Exit 3 when unsupported items remain')
    args = parser.parse_args(argv)
    try:
        model = load_model(args.model, args.allow_incomplete)
        records = select_records(model, args.variant)
    except ModelError as error:
        print(f'error: {error}', file=sys.stderr)
        return 1
    adapter = json.loads(args.adapter.read_text(encoding='utf-8')) if args.adapter else {}
    extra = json.loads(args.qt6_report.read_text())['meta'].get('components', {}) if args.qt6_report else {}
    try:
        report = generate(model, records, args.output, adapter=adapter, qt_mode=args.qt,
                          extra_components=extra, project_name=args.project_name)
    except ValueError as error:
        parser.error(str(error))
    print(json.dumps(dict(projects=len(records), unsupported=report.count('unsupported'),
                          review=report.count('review'), info=report.count('info'))))
    return 3 if args.strict and report.count('unsupported') else 0
